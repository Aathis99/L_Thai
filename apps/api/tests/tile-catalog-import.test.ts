const header = String.raw`| id | product\_code | name | shape | size\_1 | size\_2 | size\_unit | thickness\_mm | mounting\_type | description\_raw | source\_row | notes |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |`;

test('product Markdown decodes escapes while preserving all variants and unknown dimensions', () => {
  const markdown = `# Synthetic products\n\n${header}\n` + String.raw`| 1 | TEST-A | Square 1\*1 | square | 1 | 1 | in | | | 1\*1 | 4 | |
| 2 | TEST-A | Square mesh | square | 1 | 1 | in | 20 | ติดตาข่าย | 1\*1 mesh | 5 | reviewed\_note |
| 3 | TEST-B | Curve 2.25 | | 2.25 | | in | | | curve\_detail \| literal | 6 | |`;
  assert.deepEqual(parseProductsMarkdown(markdown), [
    { source_row: 4, product_code: 'TEST-A', name: 'Square 1*1', shape: 'square', size_1: 1,
      size_2: 1, size_unit: 'in', thickness_mm: null, mounting_type: null, description_raw: '1*1', notes: null },
    { source_row: 5, product_code: 'TEST-A', name: 'Square mesh', shape: 'square', size_1: 1,
      size_2: 1, size_unit: 'in', thickness_mm: 20, mounting_type: 'mesh', description_raw: '1*1 mesh', notes: 'reviewed_note' },
    { source_row: 6, product_code: 'TEST-B', name: 'Curve 2.25', shape: null, size_1: 2.25,
      size_2: null, size_unit: 'in', thickness_mm: null, mounting_type: null, description_raw: 'curve_detail | literal', notes: null },
  ]);
});

test('product Markdown rejects duplicate source rows and malformed dimensions before import', () => {
  const row = '| 1 | TEST-A | Synthetic | | 2.25 | | in | | | description | 4 | |';
  assert.throws(() => parseProductsMarkdown(`${header}\n${row}\n${row}`), /source.row|duplicate/i);
  assert.throws(() => parseProductsMarkdown(`${header}\n${row.replace('2.25', 'unknown')}`), /size_1/i);
  assert.throws(() => parseProductsMarkdown(`${header}\n${row.replace('2.25', '0')}`), /size_1/i);
  assert.throws(() => parseProductsMarkdown(`${header}\n${row.replace('TEST-A', '')}`), /product_code/i);
  assert.throws(() => parseProductsMarkdown(`${header}\n${row.replace('| in | | |', '| in | | unknown |')}`), /mounting_type/i);
  assert.throws(() => parseProductsMarkdown(`${header}\n| 1 | TEST-A |`), /column|row/i);
  assert.throws(() => parseProductsMarkdown('# no product table'), /header|table/i);
});

const integrationOptions = { skip: process.env.LTHAI_TILE_CATALOG_IMPORT_DB_TESTS !== '1'
  ? 'Set LTHAI_TILE_CATALOG_IMPORT_DB_TESTS=1 after the isolated tile catalog QA schema is ready' : false };
const syntheticRows = () => parseProductsMarkdown(`${header}\n` + String.raw`| 1 | TEST-A | Synthetic square | square | 1 | 1 | in | | | 1\*1 | 4 | |
| 2 | TEST-A | Synthetic mesh | square | 1 | 1 | in | 20 | ติดตาข่าย | 1\*1 mesh | 5 | |
| 3 | TEST-B | Synthetic curve | | 2.25 | | in | | | curve | 6 | |`);

async function fixture(t: TestContext) {
  const env = dotenv.parse(await readFile(fileURLToPath(new URL('../../../.qa/tile-catalog/qa.env', import.meta.url))));
  assert.ok(env.DATABASE_URL, 'Dedicated tile catalog QA DATABASE_URL is required');
  const control = new pg.Pool({ connectionString: env.DATABASE_URL });
  let pool: pg.Pool | undefined;
  let schema: string | undefined;
  t.after(async () => {
    await pool?.end();
    if (schema) await control.query(`DROP SCHEMA ${schema} CASCADE`);
    await control.end();
  });
  const target = (await control.query('SELECT current_database() AS database_name,current_user AS role_name')).rows[0];
  assert.equal(target.database_name, 'lthai_tile_catalog_qa', 'Importer tests must use the dedicated tile catalog QA database');
  assert.equal(target.role_name, 'lthai_tile_catalog_qa', 'Importer tests must use the dedicated QA role');
  assert.ok((await control.query("SELECT to_regclass('public.tile_products') AS product_table")).rows[0].product_table,
    'Parent tile catalog schema is not ready');
  schema = `tile_import_test_${randomUUID().replaceAll('-', '')}`;
  await control.query(`CREATE SCHEMA ${schema}`);
  await control.query(`CREATE TABLE ${schema}.tile_products (LIKE public.tile_products INCLUDING ALL)`);
  await control.query(`ALTER TABLE ${schema}.tile_products ALTER COLUMN id DROP DEFAULT, ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
  pool = new pg.Pool({ connectionString: env.DATABASE_URL, options: `-c search_path=${schema}` });
  return { pool, databaseUrl: env.DATABASE_URL, schema };
}

test('product import preserves duplicate codes, source metadata and human edits on replay', integrationOptions, async t => {
  const { pool } = await fixture(t);
  assert.deepEqual(await transaction(pool, db => importProducts(db, syntheticRows(), 'synthetic-v1')),
    { inserted: 3, unchanged: 0 });
  const before = (await pool.query('SELECT id,product_code,source_key,source_row,body_id,size_2,mounting_type,description_raw,import_fingerprint FROM tile_products ORDER BY source_row')).rows;
  assert.equal(before.length, 3);
  assert.equal(before.filter(row => row.product_code === 'TEST-A').length, 2);
  assert.equal(before[0].source_key, 'synthetic-v1:4');
  assert.equal(before[0].description_raw, '1*1');
  assert.equal(before[1].mounting_type, 'mesh');
  assert.equal(before[2].size_2, null);
  assert.ok(before.every(row => row.body_id === null && /^[a-f0-9]{64}$/.test(row.import_fingerprint)));
  await pool.query("UPDATE tile_products SET name='Human review',size_2=3,notes='Reviewed detail' WHERE source_row=6");
  assert.deepEqual(await transaction(pool, db => importProducts(db, syntheticRows(), 'synthetic-v1')),
    { inserted: 0, unchanged: 3 });
  const edited = (await pool.query('SELECT name,size_2,notes,id FROM tile_products WHERE source_row=6')).rows[0];
  assert.equal(edited.name, 'Human review');
  assert.equal(Number(edited.size_2), 3);
  assert.equal(edited.notes, 'Reviewed detail');
  assert.equal(edited.id, before[2].id);
  assert.deepEqual(await transaction(pool, db => importProducts(db, syntheticRows(), 'synthetic-v2')),
    { inserted: 3, unchanged: 0 });
});

test('product import rejects changed content and row sets atomically for an existing identity', integrationOptions, async t => {
  const { pool } = await fixture(t);
  await transaction(pool, db => importProducts(db, syntheticRows(), 'synthetic-v1'));
  const before = (await pool.query('SELECT * FROM tile_products ORDER BY id')).rows;
  const changed = syntheticRows();
  changed[2].description_raw = 'Changed source';
  await assert.rejects(transaction(pool, db => importProducts(db, changed, 'synthetic-v1')), /source.*conflict/i);
  const added = [...syntheticRows(), { ...syntheticRows()[0], source_row: 7 }];
  await assert.rejects(transaction(pool, db => importProducts(db, added, 'synthetic-v1')), /source.*conflict/i);
  await assert.rejects(transaction(pool, db => importProducts(db, syntheticRows().slice(0, 2), 'synthetic-v1')), /source.*conflict/i);
  assert.deepEqual((await pool.query('SELECT * FROM tile_products ORDER BY id')).rows, before);
  await assert.rejects(transaction(pool, db => importProducts(db, [syntheticRows()[0], syntheticRows()[0]], 'duplicate-rows')), /source.row|duplicate/i);
  assert.equal((await pool.query('SELECT count(*)::int AS count FROM tile_products')).rows[0].count, 3);
});

test('concurrent replays import the source once and retain one row per source key', integrationOptions, async t => {
  const { pool } = await fixture(t);
  const results = await Promise.all([1, 2].map(() => transaction(pool, db => importProducts(db, syntheticRows(), 'concurrent'))));
  assert.deepEqual(results.map(result => result.inserted).sort(), [0, 3]);
  assert.equal((await pool.query('SELECT count(*)::int AS count FROM tile_products')).rows[0].count, 3);
});

test('product import CLI requires explicit input and prints no source rows on failure', async () => {
  const run = promisify(execFile);
  const command = fileURLToPath(new URL('../src/tile-catalog/import-command.ts', import.meta.url));
  const directory = await mkdtemp(join(tmpdir(), 'lthai-tile-import-'));
  try {
    const source = join(directory, 'synthetic.md');
    await writeFile(source, `${header}\n| 1 | SECRET-CODE | Private source name | | 1 | | in | | | private description | 4 | |`);
    await assert.rejects(run(process.execPath, ['--import', 'tsx', command], { env: { ...process.env, DATABASE_URL: '' } }),
      (error: any) => error.code === 1 && /usage|markdown.*source/i.test(error.stderr));
    await assert.rejects(run(process.execPath, ['--import', 'tsx', command, source, 'synthetic-v1'],
      { env: { ...process.env, DATABASE_URL: '' } }), (error: any) => {
      assert.equal(error.code, 1);
      assert.match(error.stderr, /DATABASE_URL|failed/i);
      assert.doesNotMatch(error.stdout + error.stderr, /SECRET-CODE|Private source name|private description/);
      return true;
    });
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});

test('product import CLI imports only into guarded QA and reports counts', integrationOptions, async t => {
  const { pool, databaseUrl, schema } = await fixture(t);
  const run = promisify(execFile);
  const command = fileURLToPath(new URL('../src/tile-catalog/import-command.ts', import.meta.url));
  const directory = await mkdtemp(join(tmpdir(), 'lthai-tile-import-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const source = join(directory, 'synthetic.md');
  await writeFile(source, `${header}\n| 1 | TEST-CLI | Synthetic CLI | | 1 | | in | | | private description | 4 | |`);
  const connection = new URL(databaseUrl);
  connection.searchParams.set('options', `-c search_path=${schema}`);
  const env = { ...process.env, DATABASE_URL: connection.toString() };
  const first = await run(process.execPath, ['--import', 'tsx', command, source, 'synthetic-cli'], { env });
  assert.deepEqual(JSON.parse(first.stdout), { inserted: 1, unchanged: 0 });
  assert.equal(first.stderr, '');
  const second = await run(process.execPath, ['--import', 'tsx', command, source, 'synthetic-cli'], { env });
  assert.deepEqual(JSON.parse(second.stdout), { inserted: 0, unchanged: 1 });
  assert.equal((await pool.query('SELECT count(*)::int AS count FROM tile_products')).rows[0].count, 1);
});
